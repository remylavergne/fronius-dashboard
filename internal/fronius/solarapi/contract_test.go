// Contract test: the test/fixtures/solarapi fixtures are the [HYPOTHESIS] shape
// of the Solar API v1 encoded in dto.go. Any divergence between the fixture and
// the normalised model must be visible here.
//
// The test is in the external package solarapi_test: it consumes the model
// (which imports solarapi) without creating an import cycle.
