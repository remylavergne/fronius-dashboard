// Frozen instants: the simulator fixtures are generated by
// `cmd/fronius-sim --seed 42`; the other is the redacted hardware capture of
// 2026-10-16 (firmware 1.19.7-1).
var (
	syntheticInstant = time.Date(2026, 6, 21, 10, 0, 0, 0, time.UTC) // 12:00 local (+02:00)
	capturedInstant  = time.Date(2026, 10, 16, 15, 17, 23, 0, time.UTC)
	fixtureNow       = time.Date(2026, 10, 16, 12, 0, 0, 0, time.UTC)
)

func fixturePath(name string) string {
	return filepath.Join("..", "..", "..", "test", "fixtures", "solarapi", name)
}

func readFixture(t *testing.T, name string) []byte {
	t.Helper()
	body, err := os.ReadFile(fixturePath(name))
	if err != nil {
		t.Fatalf("reading %s: %v", name, err)
	}
	return body
}

func fixtureServer(t *testing.T, body []byte) *httptest.Server {
	t.Helper()
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		_, _ = w.Write(body)
	}))
	t.Cleanup(srv.Close)
	return srv
}

func fixtureClient(t *testing.T, srv *httptest.Server) *solarapi.Client {
	t.Helper()
	logger := slog.New(slog.NewTextHandler(io.Discard, nil))
	c, err := solarapi.New(srv.URL, fronius.ReadOnly{Inner: &http.Client{}}, 2*time.Second, logger)
	if err != nil {
		t.Fatalf("solarapi.New: %v", err)
	}
	return c
}

